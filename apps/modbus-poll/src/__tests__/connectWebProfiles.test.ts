import { describe, it, expect } from "vitest";
import {
  applyOps,
  buildRequest,
  canonical,
  emptyMeta,
  isDirty,
  snapshotOf,
  type ConnectStorage,
  type LocalProfile,
  type ServerProfile,
} from "../../../../packages/mt-ui/src/connectSync";
import { WEB_PROFILES } from "../../../../packages/mt-ui/src/__fixtures__/connectWebProfiles";
import { fromData, toLocal, upsertProfile } from "../connectProfiles";
import { blocksToCsv, parseBlocksCsv } from "../csv";
import { buildReadPlan, validateBlock } from "../helpers";
import type { ConnProfile } from "../types";

// Profiles built in the console's web editor must load in Modbus Poll exactly as written. The fixtures are
// generated by the console's own schema, so this exercises the real boundary: web JSON -> the app's parser,
// its Connect storage (the same upsert the useConnectSync hook runs) and the sync bookkeeping.
const modbus = WEB_PROFILES.filter((p) => p.app === "modbus-poll");

/** The hook's storage, over an in-memory list instead of the zustand store and localStorage. */
function appStorage() {
  let list: ConnProfile[] = [];
  const storage: ConnectStorage = {
    list: () => list.map(toLocal),
    upsert: ({ key, name, data }) => {
      list = upsertProfile(list, key, fromData(name, data));
      return name;
    },
    remove: (key) => {
      list = list.filter((p) => p.name !== key);
    },
  };
  return { storage, profiles: () => list };
}

const served = (p: (typeof modbus)[number], version = 1): ServerProfile => ({
  id: `web-${p.name}`,
  app: "modbus-poll",
  name: p.name,
  team_id: null,
  data: p.data,
  version,
  seq: 1,
  deleted: false,
  can_edit: true,
  updated_at: 1,
});

describe("web-edited Modbus Poll profiles", () => {
  it("has fixtures to run (guards against an empty generated file)", () => {
    expect(modbus.length).toBeGreaterThanOrEqual(3);
  });

  for (const p of modbus) {
    describe(p.name, () => {
      it("loads without losing or inventing anything", () => {
        const loaded = fromData(p.name, p.data);
        expect(loaded.name).toBe(p.name);
        expect(canonical(toLocal(loaded).data)).toBe(canonical(p.data));
      });

      it("keeps every block pollable: none is skipped when the profile is opened", () => {
        const { blocks } = fromData(p.name, p.data);
        expect(blocks.filter((b) => validateBlock(b) !== null)).toEqual([]);
        const values = blocks.reduce((n, b) => n + b.quantity, 0);
        expect(buildReadPlan(blocks).tags).toHaveLength(values);
      });

      it("downloads through sync as a clean profile: not marked changed, nothing to upload back", () => {
        const { storage, profiles } = appStorage();
        const res = applyOps([{ op: "added", profile: served(p) }], [], storage, emptyMeta(), 1, "s", 0);
        expect(profiles().map((x) => x.name)).toEqual([p.name]);
        const local = storage.list()[0] as LocalProfile;
        expect(isDirty(res.meta, local)).toBe(false);
        expect(res.meta.links[local.key]?.snapshot).toBe(snapshotOf(p.name, p.data, null));
        expect(buildRequest(storage.list(), res.meta, [], false).locals.every((l) => !l.dirty)).toBe(true);
      });

      it("replaces an older local copy with the web edit and stays clean", () => {
        const { storage } = appStorage();
        const first = applyOps([{ op: "added", profile: served(p, 1) }], [], storage, emptyMeta(), 1, "s", 0);
        const edited = { ...p.data, tcp: { ...(p.data.tcp as object), port: 1502 } };
        const res = applyOps(
          [{ op: "pulled", key: p.name, profile: { ...served(p, 2), data: edited } }],
          [],
          storage,
          first.meta,
          2,
          "s",
          0,
        );
        const local = storage.list()[0] as LocalProfile;
        expect(canonical(local.data)).toBe(canonical(edited));
        expect(isDirty(res.meta, local)).toBe(false);
      });

      it("exports the CSV the app reads, and reads the app's own CSV back to the same blocks", () => {
        const { blocks } = fromData(p.name, p.data);
        const five = blocks.map(({ name, address, quantity, type, area }) => ({ name, address, quantity, type, area }));
        // What the console wrote is exactly what the app would write...
        expect(p.csv).toBe(blocksToCsv(blocks));
        // ...and the app imports it back (extra block fields such as scale are not part of the file).
        expect(parseBlocksCsv(p.csv)).toEqual({ blocks: five, errors: [] });
      });
    });
  }
});
